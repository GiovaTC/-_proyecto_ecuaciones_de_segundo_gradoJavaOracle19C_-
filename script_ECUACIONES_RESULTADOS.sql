-- ==========================================
-- PROYECTO ECUACIONES SEGUNDO GRADO
-- ORACLE DATABASE 19C
-- ==========================================

-- CREAR TABLA
CREATE TABLE ECUACIONES_RESULTADOS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ECUACION VARCHAR2(200),
    COEFICIENTE_A NUMBER,
    COEFICIENTE_B NUMBER,
    COEFICIENTE_C NUMBER,
    DISCRIMINANTE NUMBER,
    TIPO_SOLUCION VARCHAR2(50),
    X1_REAL NUMBER,
    X1_IMAGINARIO NUMBER,
    X2_REAL NUMBER,
    X2_IMAGINARIO NUMBER,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMIT;

-- PROCEDIMIENTO ALMACENADO
CREATE OR REPLACE PROCEDURE PR_GUARDAR_ECUACION (
    P_ECUACION IN VARCHAR2,
    P_A IN NUMBER,
    P_B IN NUMBER,
    P_C IN NUMBER,
    P_DISCRIMINANTE IN NUMBER,
    P_TIPO IN VARCHAR2,
    P_X1_REAL IN NUMBER,
    P_X1_IMAG IN NUMBER,
    P_X2_REAL IN NUMBER,
    P_X2_IMAG IN NUMBER
)
AS
BEGIN

    INSERT INTO ECUACIONES_RESULTADOS (
        ECUACION,
        COEFICIENTE_A,
        COEFICIENTE_B,
        COEFICIENTE_C,
        DISCRIMINANTE,
        TIPO_SOLUCION,
        X1_REAL,
        X1_IMAGINARIO,
        X2_REAL,
        X2_IMAGINARIO
    )
    VALUES (
        P_ECUACION,
        P_A,
        P_B,
        P_C,
        P_DISCRIMINANTE,
        P_TIPO,
        P_X1_REAL,
        P_X1_IMAG,
        P_X2_REAL,
        P_X2_IMAG
    );

END;
/

COMMIT;

-- CONSULTAR REGISTROS
SELECT * FROM ECUACIONES_RESULTADOS ORDER BY ID;